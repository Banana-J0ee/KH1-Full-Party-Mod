import os
import sys, bisect
sys.path.insert(0,'.')
import codemap
from regions import pts, dd, regions, dmap
SC = os.environ.get('EPICMAP_WORK', 'work') + '/'
inst=sorted({int(l.split()[1],16) for l in open(SC+'a_calls.txt') if l.startswith('A ')}) if os.path.exists(SC+'a_calls.txt') else []
lits=sorted({int(l.split()[0],16) for l in open(SC+'lits.txt')})
extra=[0x281249c+0xdf0,0x281249c+0x1be0,0x28124a0+0xdf0,0x28124a0+0x1be0]+[0x52b0e8+8*n for n in range(4)]
need_ranges=[(0x52abb0,0x100),(0x28135e0,2*0xdf0),(0x23f09c0,0xbc0),(0x23f1590,0x20),(0x505de0,0x20),
             (0x2d37280,0x28),(0x2d534a0,0x190*4)]
px=[p[0] for p in pts]
# hex constants in the source that are sizes or flags, not addresses
NOT_ADDR={0x20000,0x40000,0x1000080,0x3af000}
def ddelta(x):
    c=dd.get(x)
    if c:
        (d,n),=[c.most_common(1)[0]]
        if len(c)>1 and n<3*sum(c.values())//4: return None,'ambiguous direct %s'%dict(c)
        return d,'direct x%d'%sum(c.values())
    m,r=dmap(x)
    if m is None: return None,'no region'
    # require neighbours on both sides within 0x400 with same delta, or inside a region
    return m-x,'region'
def span(x,d):
    # Only the bytes around an address the mod actually uses: up to the next
    # reference that moves by a different amount, and at most 0x200 bytes
    # (8 in .rdata, where the constant pools are reordered). Larger blocks the
    # mod copies are added from need_ranges after checking every reference
    # inside them.
    i=bisect.bisect_right(px,x)
    while i<len(pts) and pts[i][1]==d and pts[i][0]-x<0x200000: i+=1
    end = pts[i][0] if i<len(pts) else x+0x1000
    cap = 8 if x < 0x4d5000 else 0x200
    if os.environ.get('EPICMAP_WIDE'):   # tracing pass only: let the install run to the end
        cap = 0x200000
    return max(1, min(end - x, cap))
entries=[]; report=[]; fail=[]
code_addrs=sorted((set(a for a in inst if a<0x3af000)|set(a for a in lits if 0x1d000<=a<0x3af000))-NOT_ADDR)
for x in code_addrs:
    m,a=codemap.cmap(x)
    if m is None:
        (fail if x in inst else report).append('CODE %x unmapped'%x); continue
    entries.append((x,x+1,m-x))
data_addrs=sorted((set(a for a in inst if a>=0x3af000)|set(a for a in lits if a>0x3af000)|set(extra))-NOT_ADDR)
for x in data_addrs:
    d,why=ddelta(x)
    if d is None:
        (fail if x in inst else report).append('DATA %x %s'%(x,why)); continue
    sp=span(x,d)
    entries.append((x,x+sp,d)); report.append('DATA %x -> %x (%s) span %x'%(x,x+d,why,sp))
for base,n in need_ranges:
    d,why=ddelta(base)
    inside=[p for p in pts if base<=p[0]<base+n]
    if d is None or any(p[1]!=d for p in inside):
        fail.append('RANGE %x+%x has references that move differently'%(base,n)); continue
    entries.append((base,base+n,d)); report.append('BLOCK %x+%x delta %x (%d refs inside)'%(base,n,d,len(inside)))
# merge / clip
entries.sort()
out=[]
for lo,hi,d in entries:
    if out and lo<out[-1][1]:
        plo,phi,pd=out[-1]
        if pd==d: out[-1]=(plo,max(phi,hi),d); continue
        out[-1]=(plo,lo,pd)
    out.append((lo,hi,d))
def look(x):
    i=bisect.bisect_right([e[0] for e in out],x)-1
    return out[i][2] if i>=0 and out[i][0]<=x<out[i][1] else None
for base,n in need_ranges:
    ds={look(base+k) for k in range(0,n,4)}
    report.append('RANGE %x+%x deltas %s'%(base,n,ds))
    if len(ds)!=1 or None in ds: fail.append('RANGE %x+%x not contiguous %s'%(base,n,ds))
print('\n'.join(report)); print('FAILURES:',fail)
with open(sys.argv[1],'w') as f:
    f.write('''/* Steam RVA -> Epic RVA translation for the Epic Games Store build of
 * KINGDOM HEARTS FINAL MIX.exe. GENERATED by tools/epic_map/gen.py from a
 * function-by-function comparison of the Steam and Epic executables: every
 * code address the mod uses was matched instruction by instruction, every
 * data address through the game's own references to it. Do not edit by hand. */
#include <windows.h>
#include "kh1party.h"

int g_unmapped;

typedef struct { u32 lo, hi; s32 d; } MapRange;
static const MapRange g_map[] = {
''')
    for lo,hi,d in out: f.write('    { 0x%07x, 0x%07x, %s0x%x },\n'%(lo,hi,'-' if d<0 else '',abs(d)))
    f.write('''};

#ifdef ADDRLOG
#include <stdio.h>
#endif

u8 *game_addr(u32 rva)
{
#ifdef ADDRLOG
    fprintf(stderr, "A %x\\n", rva);
#endif
    int lo = 0, hi = (int)(sizeof g_map / sizeof g_map[0]) - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (rva < g_map[mid].lo)
            hi = mid - 1;
        else if (rva >= g_map[mid].hi)
            lo = mid + 1;
        else
            return g_base + rva + g_map[mid].d;
    }
    if (g_unmapped++ < 8)
        logf_("no Epic address for %x", rva);
    return g_base + rva;
}
''')
print('entries',len(out))
